/*
 * WLT-Settings - Config I/O backend
 * =================================
 *
 * Default persistence backend. Each category is serialised to a flat INI
 * file at /etc/wlt/<category>.conf containing only the settings that carry
 * the WLT_FLAG_PERSIST flag:
 *
 *     # WLT-Settings - network configuration
 *     network.wifi.enabled = true
 *     network.wifi.ssid = HomeNet
 *     network.tor.socks_port = 9050
 *     ...
 *
 * Writes are atomic: the file is built at <path>.tmp and renamed into
 * place, so a crash mid-write never leaves a truncated config. Reads
 * validate every value against the registry before accepting it; a single
 * corrupt line is skipped (with the default retained) rather than aborting
 * the whole load.
 *
 * This module only ever calls the public settings API, so it is fully
 * swappable (see wlt_settings_set_config_io).
 *
 * Spec: docs/specs/wlt-settings.md
 * SPDX-License-Identifier: GPL-2.0-or-later
 */
#include "settings.h"

#include <ctype.h>
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

/* ------------------------------------------------------------------ */
/* Filename mapping                                                   */
/* ------------------------------------------------------------------ */
const char *wlt_config_category_filename(wlt_category_t cat)
{
    /* Reuse the canonical lowercase category name as the file stem. */
    return wlt_settings_category_str(cat);
}

static void build_path(char *buf, size_t len, wlt_category_t cat)
{
    snprintf(buf, len, "%s/%s.conf",
             WLT_SETTINGS_CONF_DIR, wlt_config_category_filename(cat));
}

static void build_tmp_path(char *buf, size_t len, const char *final)
{
    snprintf(buf, len, "%s.tmp", final);
}

/* ------------------------------------------------------------------ */
/* String helpers                                                     */
/* ------------------------------------------------------------------ */
static char *trim(char *s)
{
    while (*s && isspace((unsigned char)*s)) s++;
    if (*s == '\0') return s;
    char *end = s + strlen(s) - 1;
    while (end > s && isspace((unsigned char)*end)) {
        *end = '\0';
        end--;
    }
    return s;
}

static bool parse_bool_str(const char *s, bool *out)
{
    if (!s) return false;
    if (strcmp(s, "true") == 0 || strcmp(s, "1") == 0 ||
        strcmp(s, "yes") == 0 || strcmp(s, "on") == 0) {
        *out = true;  return true;
    }
    if (strcmp(s, "false") == 0 || strcmp(s, "0") == 0 ||
        strcmp(s, "no") == 0 || strcmp(s, "off") == 0) {
        *out = false; return true;
    }
    return false;
}

/* Format a value into buf according to its type. Returns bytes written. */
static int format_value(char *buf, size_t len,
                        const wlt_setting_entry_t *e)
{
    switch (e->desc.type) {
    case WLT_TYPE_BOOL:
        return snprintf(buf, len, "%s", e->value.b ? "true" : "false");
    case WLT_TYPE_INT:
        return snprintf(buf, len, "%lld", (long long)e->value.i);
    case WLT_TYPE_FLOAT:
        return snprintf(buf, len, "%.6g", e->value.f);
    case WLT_TYPE_STRING:
    case WLT_TYPE_ENUM:
        return snprintf(buf, len, "%s", e->value.s);
    default:
        return 0;
    }
}

/* ------------------------------------------------------------------ */
/* Save                                                               */
/* ------------------------------------------------------------------ */
static wlt_settings_err_t wlt_config_save_category(wlt_settings_t *s,
                                                   wlt_category_t cat)
{
    if (!s) return WLT_SETTINGS_ERR_INVALID;
    if (cat < 0 || cat >= WLT_CAT_COUNT) return WLT_SETTINGS_ERR_INVALID;

    char path[512];
    char tmp[520];
    build_path(path, sizeof(path), cat);
    build_tmp_path(tmp, sizeof(tmp), path);

    FILE *fp = fopen(tmp, "w");
    if (!fp)
        return (errno == EACCES || errno == EROFS) ? WLT_SETTINGS_ERR_PERM
                                                   : WLT_SETTINGS_ERR_IO;

    fprintf(fp, "# WLT-Settings - %s configuration\n",
            wlt_settings_category_str(cat));
    fprintf(fp, "# Generated by wlt-settings; do not edit by hand.\n");

    /* Iterate via the public API only (the manager struct is opaque here). */
    const wlt_setting_entry_t *base = NULL;
    size_t match = 0;
    if (wlt_settings_list_by_category(s, cat, &base, &match) != WLT_SETTINGS_OK) {
        fclose(fp);
        remove(tmp);
        return WLT_SETTINGS_ERR_INVALID;
    }
    size_t total = wlt_settings_count(s);

    wlt_settings_err_t worst = WLT_SETTINGS_OK;
    for (size_t i = 0; i < total; i++) {
        const wlt_setting_entry_t *e = &base[i];
        if (e->desc.category != cat)
            continue;
        if (!(e->desc.flags & WLT_FLAG_PERSIST))
            continue;
        if (e->desc.flags & WLT_FLAG_READONLY)
            continue;                       /* never persist read-only state */

        char val[WLT_SETTINGS_STR_MAX];
        format_value(val, sizeof(val), e);

        if (fprintf(fp, "%s = %s\n", e->desc.key, val) < 0) {
            worst = WLT_SETTINGS_ERR_IO;
            break;
        }
    }

    if (fclose(fp) != 0)
        worst = WLT_SETTINGS_ERR_IO;

    if (worst != WLT_SETTINGS_OK) {
        remove(tmp);
        return worst;
    }

    /* Atomic publish. */
    if (rename(tmp, path) != 0) {
        remove(tmp);
        return (errno == EACCES || errno == EROFS) ? WLT_SETTINGS_ERR_PERM
                                                   : WLT_SETTINGS_ERR_IO;
    }
    chmod(path, 0644);
    return WLT_SETTINGS_OK;
}

/* ------------------------------------------------------------------ */
/* Load                                                               */
/* ------------------------------------------------------------------ */
/*
 * Parse one "key = value" line and push it through the backend hook.
 * Unknown keys / type mismatches / out-of-range values are skipped so a
 * partially-corrupt file degrades gracefully.
 */
static void apply_line(wlt_settings_t *s, char *line)
{
    char *eq = strchr(line, '=');
    if (!eq) return;
    *eq = '\0';
    char *key = trim(line);
    char *val = trim(eq + 1);
    if (key[0] == '\0')
        return;

    const wlt_setting_entry_t *e = NULL;
    if (wlt_settings_find(s, key, &e) != WLT_SETTINGS_OK)
        return;                            /* unknown key, ignore */

    wlt_value_t v;
    memset(&v, 0, sizeof(v));

    switch (e->desc.type) {
    case WLT_TYPE_BOOL: {
        bool b;
        if (!parse_bool_str(val, &b)) return;
        v.b = b;
        break;
    }
    case WLT_TYPE_INT: {
        errno = 0;
        char *end = NULL;
        long long n = strtoll(val, &end, 10);
        if (errno != 0 || end == val) return;
        v.i = (int64_t)n;
        break;
    }
    case WLT_TYPE_FLOAT: {
        errno = 0;
        char *end = NULL;
        double d = strtod(val, &end);
        if (errno != 0 || end == val) return;
        v.f = d;
        break;
    }
    case WLT_TYPE_STRING:
    case WLT_TYPE_ENUM:
        strncpy(v.s, val, WLT_SETTINGS_STR_MAX - 1);
        v.s[WLT_SETTINGS_STR_MAX - 1] = '\0';
        break;
    default:
        return;
    }

    /* load_value validates + clears dirty + emits LOADED. A validation
     * failure (bad range/enum) just drops the line. */
    (void)wlt_settings_load_value(s, key, &v, e->desc.type);
}

static wlt_settings_err_t wlt_config_load_category(wlt_settings_t *s,
                                                   wlt_category_t cat)
{
    if (!s) return WLT_SETTINGS_ERR_INVALID;
    if (cat < 0 || cat >= WLT_CAT_COUNT) return WLT_SETTINGS_ERR_INVALID;

    char path[512];
    build_path(path, sizeof(path), cat);

    FILE *fp = fopen(path, "r");
    if (!fp) {
        /* No stored config: keep registered defaults. Not an error. */
        if (errno == ENOENT) return WLT_SETTINGS_OK;
        return (errno == EACCES) ? WLT_SETTINGS_ERR_PERM
                                 : WLT_SETTINGS_ERR_IO;
    }

    char line[1024];
    while (fgets(line, sizeof(line), fp)) {
        /* Strip trailing newline. */
        size_t n = strlen(line);
        while (n > 0 && (line[n - 1] == '\n' || line[n - 1] == '\r')) {
            line[--n] = '\0';
        }
        char *t = trim(line);
        if (*t == '\0' || *t == '#' || *t == ';')
            continue;
        apply_line(s, t);
    }

    if (ferror(fp)) {
        fclose(fp);
        return WLT_SETTINGS_ERR_IO;
    }
    fclose(fp);
    return WLT_SETTINGS_OK;
}

/* ------------------------------------------------------------------ */
/* Backend export (strong definition overrides the weak one in core)  */
/* ------------------------------------------------------------------ */
const wlt_config_io_t wlt_default_config_io = {
    .load_category = wlt_config_load_category,
    .save_category = wlt_config_save_category
};
