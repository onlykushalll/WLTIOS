static int create_shm(void) {
    int stride=WIN_W*4, size=stride*WIN_H;
    char t[]="/run/wlt-bar-shm-XXXXXX";
    int fd=mkostemp(t,O_CLOEXEC); if(fd<0) return -1; unlink(t);
    if(ftruncate(fd,size)<0){close(fd);return -1;}
    shm_pixels=mmap(NULL,size,PROT_READ|PROT_WRITE,MAP_SHARED,fd,0);
    if(shm_pixels==MAP_FAILED){close(fd);return -1;}
    struct wl_shm_pool*p=wl_shm_create_pool(shm,fd,size);
    buffer=wl_shm_pool_create_buffer(p,0,WIN_W,WIN_H,stride,WL_SHM_FORMAT_XRGB8888);
    wl_shm_pool_destroy(p); return 0;
}

static void px(int x,int y,uint8_t r,uint8_t g,uint8_t b) {
    if(x<0||x>=WIN_W||y<0||y>=WIN_H) return;
    shm_pixels[y*WIN_W+x]=(0xFF<<24)|(r<<16)|(g<<8)|b;
}

static void draw_char(int px_,int py,char ch,uint8_t r,uint8_t g,uint8_t b) {
    int idx=ch-32; if(idx<0||idx>=96) idx=0;
    const uint8_t*gl=font8x16[idx];
    for(int row=0;row<FONT_H;row++){uint8_t bits=gl[row];
        for(int col=0;col<FONT_W;col++)
            if(bits&(0x80>>col)) px(px_+col,py+row,r,g,b);
    }
}

static void draw_text(int x,int y,const char*s,uint8_t r,uint8_t g,uint8_t b) {
    for(const char*c=s;*c;c++){draw_char(x,y,*c,r,g,b);x+=FONT_W+1;}
}

/* Read real system state */
static int tor_running(void) {
    FILE *f=fopen("/run/tor.pid","r");
    if(!f) return 0;
    int pid; if(fscanf(f,"%d",&pid)!=1){fclose(f);return 0;} fclose(f);
    char path[64]; snprintf(path,sizeof(path),"/proc/%d/comm",pid);
    f=fopen(path,"r"); if(!f) return 0;
    char comm[32]; int ok=fscanf(f,"%31s",comm)==1; fclose(f);
    return ok && strstr(comm,"tor");
}

static int net_up(void) {
    FILE *f=fopen("/sys/class/net/eth0/operstate","r");
    if(!f) return 0;
    char state[32]; int ok=fscanf(f,"%31s",state)==1; fclose(f);
    return ok && !strcmp(state,"up");
}

static int ram_percent(void) {
    FILE *f=fopen("/proc/meminfo","r"); if(!f) return 0;
    long total=0, avail=0; char line[256];
    while(fgets(line,sizeof(line),f)) {
        if(strstr(line,"MemTotal:")) sscanf(line+9,"%ld",&total);
        else if(strstr(line,"MemAvailable:")) sscanf(line+13,"%ld",&avail);
    }
    fclose(f);
    if(total<=0) return 0;
    return (int)((total-avail)*100/total);
}

static double uptime(void) {
    FILE *f=fopen("/proc/uptime","r"); if(!f) return 0;
    double up; fscanf(f,"%lf",&up); fclose(f); return up;
}

/* Scan /proc for known WLTIOS apps and collect their labels.
 * Returns count of running apps found (deduplicated — each label appears once).
 * labels[] filled with up to MAX_RUNNING non-NULL pointers. */
static int scan_running_apps(const char *labels[MAX_RUNNING]) {
    DIR *proc = opendir("/proc");
    if(!proc) return 0;

    int count = 0;
    char seen[16] = {0};  /* one byte per tracked app */
    int n_apps = 0;
    while(TRACKED_APPS[n_apps].comm) n_apps++;

    struct dirent *e;
    while((e = readdir(proc)) != NULL) {
        /* only numeric dir entries = PIDs */
        if(!isdigit((unsigned char)e->d_name[0])) continue;

        char path[64];
        snprintf(path, sizeof(path), "/proc/%.20s/comm", e->d_name);
        FILE *f = fopen(path, "r");
        if(!f) continue;
        char comm[32] = {0};
        if(fscanf(f, "%31s", comm) != 1) { fclose(f); continue; }
        fclose(f);

        for(int i = 0; i < n_apps; i++) {
            if(seen[i]) continue;
            /* /proc/<pid>/comm is the bare executable name (no path),
             * truncated to 15 chars by the kernel. Match exactly. */
            if(strcmp(comm, TRACKED_APPS[i].comm) == 0) {
                if(count < MAX_RUNNING) {
                    labels[count++] = TRACKED_APPS[i].label;
                }
                seen[i] = 1;
                break;
            }
        }
    }
    closedir(proc);
    return count;
}

static void render(void) {
    /* Dark bar background */
    for(int y=0;y<WIN_H;y++) for(int x=0;x<WIN_W;x++)
        px(x,y,0x20,0x20,0x30);

    /* WLTIOS title (white, left) */
    draw_text(8, 8, "WLTIOS 0.1.0", 0xFF,0xFF,0xFF);

    /* Tor status (left of center) */
    int tor=tor_running();
    draw_text(200, 8, tor?"TOR: ON":"TOR: OFF", tor?0x00:0xFF, tor?0xFF:0x44, 0x00);

    /* Network status */
    int net=net_up();
    draw_text(350, 8, net?"NET: UP":"NET: DOWN", net?0x00:0xFF, net?0xFF:0x44, 0x00);

    /* RAM usage */
    int ram=ram_percent();
    char ram_str[32]; snprintf(ram_str,sizeof(ram_str),"RAM: %d%%",ram);
    uint8_t ram_r = ram>80?0xFF:0x00, ram_g = ram>80?0x44:0xFF;
    draw_text(500, 8, ram_str, ram_r, ram_g, 0x00);

    /* ─── Taskbar: running-app list (middle of bar) ───
     * Per wlt-shell.md spec: [Start] [App1] [App2] [App3] ... [Tor] [Net] [Bat] [Clock]
     * We render: "RUN:" followed by each tracked app label in brackets. */
    const char *labels[MAX_RUNNING] = {0};
    int n = scan_running_apps(labels);
    int tx = 640;
    draw_text(tx, 8, "RUN:", 0xC0,0xC0,0xD0);
    tx += 5 * (FONT_W + 1);
    if(n == 0) {
        draw_text(tx, 8, "(none)", 0x70,0x70,0x80);
    } else {
        for(int i = 0; i < n && i < MAX_RUNNING; i++) {
            char buf[24];
            snprintf(buf, sizeof(buf), "[%s]", labels[i]);
            /* Cyan highlight for running apps */
            draw_text(tx, 8, buf, 0x00,0xC0,0xE0);
            tx += (int)strlen(buf) * (FONT_W + 1) + 4;
            if(tx > WIN_W - 200) break;  /* leave room for uptime */
        }
    }

    /* Uptime (right side) */
    double up=uptime();
    unsigned h=(unsigned)(up/3600), m=((unsigned)up%3600)/60, s=(unsigned)up%60;
    char up_str[32]; snprintf(up_str,sizeof(up_str),"UP: %02u:%02u:%02u",h,m,s);
    draw_text(WIN_W-160, 8, up_str, 0xC0,0xC0,0xD0);
}

int main(void) {
    fprintf(stderr,"[statusbar] starting\n");
    signal(SIGTERM,on_sig); signal(SIGINT,on_sig);

    display=wl_display_connect(NULL);
    if(!display){fprintf(stderr,"[statusbar] FATAL: no Wayland\n");return 1;}
    struct wl_registry*reg=wl_display_get_registry(display);
    wl_registry_add_listener(reg,&rl,NULL); wl_display_roundtrip(display);
    if(!compositor||!shm||!xdg_wm_base){fprintf(stderr,"[statusbar] FATAL: missing globals\n");return 1;}
    xdg_wm_base_add_listener(xdg_wm_base,&xwml,NULL);
    if(create_shm()<0){fprintf(stderr,"[statusbar] FATAL: no buffer\n");return 1;}
    surface=wl_compositor_create_surface(compositor);
    xdg_surface=xdg_wm_base_get_xdg_surface(xdg_wm_base,surface);
    xdg_surface_add_listener(xdg_surface,&xsl,NULL);
    xdg_toplevel=xdg_surface_get_toplevel(xdg_surface);
    xdg_toplevel_add_listener(xdg_toplevel,&xtl,NULL);
    xdg_toplevel_set_title(xdg_toplevel,"WLTIOS Status Bar");
    wl_surface_commit(surface); wl_display_roundtrip(display);
    fprintf(stderr,"[statusbar] surface created\n");

    int frame_count=0;
    while(running) {
        while(wl_display_prepare_read(display)!=0) wl_display_dispatch_pending(display);
        wl_display_flush(display); wl_display_read_events(display); wl_display_dispatch_pending(display);
        usleep(1000000); /* 1fps — status bar doesn't need high fps */

        if(configured) {
            render();
            wl_surface_attach(surface,buffer,0,0);
            wl_surface_damage(surface,0,0,WIN_W,WIN_H);
            wl_surface_commit(surface);
            frame_count++;
            if(frame_count<=3) fprintf(stderr,"[statusbar] frame %d rendered\n",frame_count);
        }
    }
    fprintf(stderr,"[statusbar] exiting\n");
    return 0;
}
