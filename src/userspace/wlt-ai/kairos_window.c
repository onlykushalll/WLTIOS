/**
 * @file kairos_window.c
 * @brief Kairos AI assistant — Wayland window with chat interface
 * @purpose Persistent panel for AI chat, calls existing kairos CLI
 *
 * Same Wayland client pattern as wlt-term-wayland.c:
 *   connect → registry → bind → surface → shm buffer → render → commit
 *
 * Chat interface:
 *   - Chat history (green text on black, kernel font_8x16 at 2x)
 *   - Input line at bottom
 *   - Enter: fork kairos CLI, capture output, display
 *   - The model stays Qwen2.5-1.5B (already running via llama-server)
 *
 * Build: gcc -O2 $(pkg-config --cflags wayland-client) kairos_window.c \
 *          xdg-shell-client-protocol.c $(pkg-config --libs wayland-client) -o kairos-window
 */

