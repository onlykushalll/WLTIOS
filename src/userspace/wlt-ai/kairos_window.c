static const struct xdg_toplevel_listener xtl={.configure=xt_conf,.close=xt_close};

static int create_shm(void) {
    int stride=WIN_W*4, size=stride*WIN_H;
    char t[]="/run/kairos-shm-XXXXXX";
    int fd=mkostemp(t,O_CLOEXEC); if(fd<0) return -1; unlink(t);
    if(ftruncate(fd,size)<0){close(fd);return -1;}
    shm_pixels=mmap(NULL,size,PROT_READ|PROT_WRITE,MAP_SHARED,fd,0);
    if(shm_pixels==MAP_FAILED){close(fd);return -1;}
    struct wl_shm_pool*p=wl_shm_create_pool(shm,fd,size);
    buffer=wl_shm_pool_create_buffer(p,0,WIN_W,WIN_H,stride,WL_SHM_FORMAT_XRGB8888);
    wl_shm_pool_destroy(p); return 0;
}

static void px(int x,int y,uint8_t r,uint8_t g,uint8_t b) {
    if(x<0||x>=WIN_W||y<0||y>=WIN_H) return;
    shm_pixels[y*WIN_W+x]=(0xFF<<24)|(r<<16)|(g<<8)|b;
}

static void draw_char(int px_,int py,char ch,uint8_t r,uint8_t g,uint8_t b) {
    int idx=ch-32; if(idx<0||idx>=96) idx=0;
    const uint8_t*gl=font8x16[idx];
    for(int row=0;row<FONT_H;row++){uint8_t bits=gl[row];
        for(int col=0;col<FONT_W;col++)
            if(bits&(0x80>>col))
                for(int sy=0;sy<SCALE;sy++)
                    for(int sx=0;sx<SCALE;sx++)
                        px(px_+col*SCALE+sx,py+row*SCALE+sy,r,g,b);
    }
}

static void draw_text(int x,int y,const char*s,uint8_t r,uint8_t g,uint8_t b) {
    for(const char*c=s;*c;c++){draw_char(x,y,*c,r,g,b);x+=CELL_W;}
}

static void add_chat_line(const char *text) {
    if (chat_row >= ROWS - 1) {
        /* Scroll up */
        memmove(chat_lines[0], chat_lines[1], sizeof(chat_lines) - sizeof(chat_lines[0]));
        memset(chat_lines[ROWS-1], ' ', COLS);
        chat_row = ROWS - 1;
    }
    memset(chat_lines[chat_row], ' ', COLS);
    strncpy(chat_lines[chat_row], text, COLS - 1);
    chat_row++;
}

static void send_query(void) {
    if (input_len == 0) return;
    input_buf[input_len] = '\0';

    /* Display user message */
    char user_msg[COLS + 8];
    snprintf(user_msg, sizeof(user_msg), "> %s", input_buf);
    add_chat_line(user_msg);
    add_chat_line("  (querying kairos...)");

    /* Call the in-process AI engine (libwlt-ai.a).
     * Replaces the old fork+execl("/bin/sh"...) path - no shell,
     * no external CLI. wlt_ai_query -> wlt_llm_call_local ->
     * wlt_http_post (raw socket to 127.0.0.1:8080). */
    if (ai_ctx == NULL) {
        add_chat_line("  (AI engine not initialized)");
    } else {
        wlt_ai_response_t resp = wlt_ai_query(ai_ctx, input_buf);

        if (resp.error != WLT_AI_OK) {
            add_chat_line("  (AI error)");
        } else if (resp.text[0] != '\0') {
            /* Split response into lines (COLS-1 chars each) */
            char buf[WLT_AI_MAX_RESPONSE];
            strncpy(buf, resp.text, sizeof(buf) - 1);
            buf[sizeof(buf) - 1] = '\0';
            char *line = strtok(buf, "\n");
            while (line && chat_row < ROWS - 1) {
                /* Truncate over-long lines to COLS-1 */
                char row[COLS];
                strncpy(row, line, COLS - 1);
                row[COLS - 1] = '\0';
                add_chat_line(row);
                line = strtok(NULL, "\n");
            }
        } else {
            add_chat_line("  (empty response)");
        }
    }

    /* Clear input */
    input_len = 0;
    input_buf[0] = '\0';
    needs_redraw = 1;
}

/* --- Keyboard handling (wl_keyboard listener) ---
 * Without this, send_query() was dead code — the window never
 * received keypresses. Now Enter sends the query, Backspace
 * deletes, and printable chars append to the input buffer.
 * Uses raw evdev keycodes (no xkb keymap — minimal but works). */
static void kb_keymap(void*d,struct wl_keyboard*k,uint32_t f,int32_t fd,uint32_t s){
    (void)d;(void)k;(void)f;(void)s; close(fd); /* no xkb — raw keycodes */
}
static void kb_enter(void*d,struct wl_keyboard*k,uint32_t s,struct wl_surface*sf,struct wl_array*keys){(void)d;(void)k;(void)s;(void)sf;(void)keys;}
static void kb_leave(void*d,struct wl_keyboard*k,uint32_t s,struct wl_surface*sf){(void)d;(void)k;(void)s;(void)sf;}
static void kb_mod(void*d,struct wl_keyboard*k,uint32_t s,uint32_t dp,uint32_t l,uint32_t g,uint32_t lg){(void)d;(void)k;(void)s;(void)dp;(void)l;(void)g;(void)lg;}
static void kb_rep(void*d,struct wl_keyboard*k,int32_t r,int32_t dly){(void)d;(void)k;(void)r;(void)dly;}

static void kb_key(void*d,struct wl_keyboard*k,uint32_t serial,
                   uint32_t time,uint32_t key,uint32_t state){
    (void)d;(void)k;(void)serial;(void)time;
    if(state!=WL_KEYBOARD_KEY_STATE_PRESSED) return;

    if(key==28){ /* Enter */
        send_query();
    } else if(key==14){ /* Backspace */
        if(input_len>0){ input_len--; input_buf[input_len]='\0'; needs_redraw=1; }
    } else if(key==57){ /* Space */
        if(input_len<COLS-1){ input_buf[input_len++]=' '; input_buf[input_len]='\0'; needs_redraw=1; }
    } else if(key>=30&&key<=58&&input_len<COLS-1){ /* a-z (evdev 30-58) */
        char c='a'+(key-30);
        input_buf[input_len++]=c;
        input_buf[input_len]='\0';
        needs_redraw=1;
    } else if(key>=2&&key<=11&&input_len<COLS-1){ /* 1-9,0 (evdev 2-11) */
        char c=(key==11)?'0':('1'+(key-2));
        input_buf[input_len++]=c;
        input_buf[input_len]='\0';
        needs_redraw=1;
    }
}
static const struct wl_keyboard_listener kbl={
    .keymap=kb_keymap,.enter=kb_enter,.leave=kb_leave,
    .key=kb_key,.modifiers=kb_mod,.repeat_info=kb_rep
};
static void seat_caps(void*d,struct wl_seat*s,uint32_t caps){
    (void)d;
    if((caps&WL_SEAT_CAPABILITY_KEYBOARD)&&!keyboard){
        keyboard=wl_seat_get_keyboard(s);
        wl_keyboard_add_listener(keyboard,&kbl,NULL);
    }
}
static void seat_name(void*d,struct wl_seat*s,const char*n){(void)d;(void)s;(void)n;}
static const struct wl_seat_listener seatl={.capabilities=seat_caps,.name=seat_name};

static void render(void) {
    /* Background: dark teal */
    for(int y=0;y<WIN_H;y++) for(int x=0;x<WIN_W;x++)
        px(x,y,0x10,0x20,0x20);
    /* Border: cyan */
    for(int y=0;y<4;y++) for(int x=0;x<WIN_W;x++){px(x,y,0x00,0xC0,0xC0);px(x,WIN_H-1-y,0x00,0xC0,0xC0);}
    for(int x=0;x<4;x++) for(int y=0;y<WIN_H;y++){px(x,y,0x00,0xC0,0xC0);px(WIN_W-1-x,y,0x00,0xC0,0xC0);}

    /* Title */
    draw_text(8, 4, "Kairos AI Assistant", 0x00, 0xFF, 0xFF);

    /* Chat history (green text) */
    for (int r = 0; r < ROWS; r++) {
        int y = 4 + (r + 1) * CELL_H;
        for (int c = 0; c < COLS; c++) {
            char ch = chat_lines[r][c];
            if (ch && ch != ' ') {
                draw_char(4 + c * CELL_W, y, ch, 0x00, 0xFF, 0x00);
            }
        }
    }

    /* Input line (yellow) */
    int input_y = 4 + (ROWS + 1) * CELL_H;
    draw_text(4, input_y, ">", 0xFF, 0xFF, 0x00);
    draw_text(4 + CELL_W, input_y, input_buf, 0xFF, 0xFF, 0x00);
    /* Cursor */
    draw_char(4 + (input_len + 1) * CELL_W, input_y, '_', 0xFF, 0xFF, 0x00);
}

int main(void) {
    fprintf(stderr,"[kairos] starting\n");
    signal(SIGTERM,on_sig); signal(SIGINT,on_sig);

    display=wl_display_connect(NULL);
    if(!display){fprintf(stderr,"[kairos] FATAL: no Wayland\n");return 1;}
    struct wl_registry*reg=wl_display_get_registry(display);
    wl_registry_add_listener(reg,&rl,NULL); wl_display_roundtrip(display);
    if(!compositor||!shm||!xdg_wm_base){fprintf(stderr,"[kairos] FATAL: missing globals\n");return 1;}
    if(seat){
        wl_seat_add_listener(seat,&seatl,NULL);
        wl_display_roundtrip(display);
    }
    xdg_wm_base_add_listener(xdg_wm_base,&xwml,NULL);
    if(create_shm()<0){fprintf(stderr,"[kairos] FATAL: no buffer\n");return 1;}
    surface=wl_compositor_create_surface(compositor);
    xdg_surface=xdg_wm_base_get_xdg_surface(xdg_wm_base,surface);
    xdg_surface_add_listener(xdg_surface,&xsl,NULL);
    xdg_toplevel=xdg_surface_get_toplevel(xdg_surface);
    xdg_toplevel_add_listener(xdg_toplevel,&xtl,NULL);
    xdg_toplevel_set_title(xdg_toplevel,"Kairos AI");
    wl_surface_commit(surface); wl_display_roundtrip(display);
    fprintf(stderr,"[kairos] surface created\n");

    /* Welcome message */
    add_chat_line("Kairos AI Assistant v1.0");
    add_chat_line("Type a command and press Enter");
    add_chat_line("(Model: Qwen2.5-1.5B via llama-server)");
    add_chat_line("");

    /* Initialize the in-process AI engine (libwlt-ai.a).
     * Local mode, amnesic memory, loopback endpoint for llama-server. */
    wlt_ai_config_t cfg;
    memset(&cfg, 0, sizeof(cfg));
    cfg.enabled = true;
    cfg.mode = WLT_AI_MODE_LOCAL;
    cfg.memory_mode = WLT_AI_MEMORY_AMNESIC;
    /* QEMU: 10.0.2.2 is the host (QEMU gateway). Production: 127.0.0.1. */
    const char *llm_ep = getenv("WLT_AI_LLM_ENDPOINT");
    if (!llm_ep) llm_ep = "http://10.0.2.2:8080";
    strncpy(cfg.local_llm_endpoint, llm_ep, sizeof(cfg.local_llm_endpoint) - 1);
    strncpy(cfg.llm_model, "qwen2.5-1.5b", sizeof(cfg.llm_model) - 1);
    ai_ctx = wlt_ai_init(&cfg);
    if (ai_ctx == NULL) {
        fprintf(stderr, "[kairos] WARNING: AI engine init failed "
                "(queries will show error)\n");
        add_chat_line("(AI engine init failed)");
    } else {
        fprintf(stderr, "[kairos] AI engine ready (local LLM)\n");
    }

    /* Test mode: auto-send a query if /etc/wlt-ai-test exists */
    const char *test_q = NULL;
    {
        FILE *tf = fopen("/etc/wlt-ai-test", "r");
        if (tf) {
            static char test_buf[256];
            if (fgets(test_buf, sizeof(test_buf), tf)) {
                char *nl = strchr(test_buf, '\n');
                if (nl) *nl = '\0';
                test_q = test_buf;
            }
            fclose(tf);
        }
    }
    if (test_q && ai_ctx) {
        fprintf(stderr, "[kairos] TEST QUERY: %s\n", test_q);
        strncpy(input_buf, test_q, COLS - 1);
        input_len = strlen(input_buf);
        send_query();
        needs_redraw = 1;
    }

    while(running) {
        while(wl_display_prepare_read(display)!=0) wl_display_dispatch_pending(display);
        wl_display_flush(display); wl_display_read_events(display); wl_display_dispatch_pending(display);
        usleep(33000);

        if(needs_redraw && configured) {
            render();
            wl_surface_attach(surface,buffer,0,0);
            wl_surface_damage(surface,0,0,WIN_W,WIN_H);
            wl_surface_commit(surface);
            needs_redraw=0;
        }
    }
    if (ai_ctx != NULL) {
        wlt_ai_shutdown(ai_ctx);
        ai_ctx = NULL;
    }
    fprintf(stderr,"[kairos] exiting\n");
    return 0;
}
