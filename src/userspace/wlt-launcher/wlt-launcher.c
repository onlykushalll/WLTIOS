/**
 * @file wlt-launcher.c
 * @brief WLTIOS App Launcher — minimal overlay listing available apps
 * @purpose Keyboard-triggered launcher that spawns terminal/file-manager via fork+exec
 *
 * Reuses the exact Wayland client pattern from wlt-term-wayland.c:
 *   connect → registry → bind compositor+shm+xdg_wm_base → create surface →
 *   create shm buffer → render → commit
 *
 * The launcher is a small 400x300 window with a list of apps.
 * Arrow keys navigate, Enter spawns, Esc closes.
 *
 * Build: gcc -O2 $(pkg-config --cflags wayland-client) wlt-launcher.c \
 *          xdg-shell-client-protocol.c $(pkg-config --libs wayland-client) -o wlt-launcher
 */

