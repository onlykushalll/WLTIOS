/* ─── Palette Setup ──────────────────────────────────── */

void
wlt_render_init_palette(wlt_Terminal *term, const wlt_Config *config)
{
    if (term == NULL) return;

    if (config != NULL)
    {
        memcpy(term->palette, config->palette, sizeof(term->palette));
        term->default_fg = config->default_fg;
        term->default_bg = config->default_bg;
        term->cursor_color = config->cursor_color;
        term->selection_color = config->selection_color;
    }
    else
    {
        memcpy(term->palette, DEFAULT_PALETTE, sizeof(DEFAULT_PALETTE));
        term->default_fg = DEFAULT_FG;
        term->default_bg = DEFAULT_BG;
        term->cursor_color = DEFAULT_CURSOR;
        term->selection_color = DEFAULT_SEL;
    }
}

uint8_t
wlt_render_nearest_palette(const wlt_Terminal *term,
                           uint8_t r, uint8_t g, uint8_t b)
{
    if (term == NULL) return 7;

    uint8_t best = 0;
    uint32_t best_dist = UINT32_MAX;
    for (int i = 0; i < WLT_TERMINAL_NUM_COLORS; i++)
    {
        int dr = (int)r - (int)term->palette[i].r;
        int dg = (int)g - (int)term->palette[i].g;
        int db = (int)b - (int)term->palette[i].b;
        uint32_t d = (uint32_t)(dr * dr + dg * dg + db * db);
        if (d < best_dist)
        {
            best_dist = d;
            best = (uint8_t)i;
        }
    }
    return best;
}

/* ─── Pixel Helpers ──────────────────────────────────── */

static inline void
put_pixel(wlt_Framebuffer *fb, uint32_t x, uint32_t y, wlt_Color c)
{
    if (x >= fb->width || y >= fb->height) return;
    uint32_t off = y * fb->stride + x * fb->bytes_per_pixel;
    if (off + 3 >= fb->stride * fb->height) return;
    /* BGRA */
    fb->data[off + 0] = c.b;
    fb->data[off + 1] = c.g;
    fb->data[off + 2] = c.r;
    if (fb->bytes_per_pixel == 4)
        fb->data[off + 3] = 0xFF;
}

static void
fill_rect(wlt_Framebuffer *fb,
          uint32_t x0, uint32_t y0,
          uint32_t w, uint32_t h, wlt_Color c)
{
    for (uint32_t y = y0; y < y0 + h && y < fb->height; y++)
        for (uint32_t x = x0; x < x0 + w && x < fb->width; x++)
            put_pixel(fb, x, y, c);
}

static wlt_Color
cell_fg(const wlt_Terminal *term, const wlt_Cell *cell)
{
    wlt_Color c = (cell->fg < WLT_TERMINAL_NUM_COLORS)
        ? term->palette[cell->fg] : term->default_fg;
    return c;
}

static wlt_Color
cell_bg(const wlt_Terminal *term, const wlt_Cell *cell)
{
    wlt_Color c = (cell->bg < WLT_TERMINAL_NUM_COLORS)
        ? term->palette[cell->bg] : term->default_bg;
    return c;
}

static void
swap_colors(wlt_Color *a, wlt_Color *b)
{
    wlt_Color t = *a; *a = *b; *b = t;
}

/* ─── Glyph Drawing ──────────────────────────────────── */

static void
draw_glyph(wlt_Framebuffer *fb,
           uint32_t ox, uint32_t oy,
           uint32_t codepoint,
           wlt_Color fg, wlt_Color bg,
          bool bold, bool underline)
{
    /* Fill cell background */
    fill_rect(fb, ox, oy, WLT_RENDER_CELL_W, WLT_RENDER_CELL_H, bg);

    const uint8_t *glyph = NULL;
    if (codepoint >= 0x20 && codepoint < 0x80)
        glyph = FONT8X8[codepoint - 0x20];

    if (glyph == NULL)
    {
        /* Outside our font range: draw a small hollow box as placeholder */
        wlt_Color dim = fg;
        for (uint32_t y = 0; y < WLT_RENDER_FONT_H; y++)
        {
            put_pixel(fb, ox + 0, oy + y, dim);
            put_pixel(fb, ox + WLT_RENDER_FONT_W - 1, oy + y, dim);
        }
        for (uint32_t x = 0; x < WLT_RENDER_FONT_W; x++)
        {
            put_pixel(fb, ox + x, oy + 0, dim);
            put_pixel(fb, ox + x, oy + WLT_RENDER_FONT_H - 1, dim);
        }
        return;
    }

    /* Draw the 8x8 glyph bits */
    for (uint32_t y = 0; y < WLT_RENDER_FONT_H; y++)
    {
        uint8_t row = glyph[y];
        if (bold)
            row |= (row >> 1);  /* Smear right for bold */
        for (uint32_t x = 0; x < WLT_RENDER_FONT_W; x++)
        {
            if (row & (0x80 >> x))
                put_pixel(fb, ox + x, oy + y, fg);
        }
    }

    if (underline)
    {
        for (uint32_t x = 0; x < WLT_RENDER_FONT_W; x++)
            put_pixel(fb, ox + x, oy + WLT_RENDER_FONT_H - 1, fg);
    }
}

/* ─── Cursor Drawing ─────────────────────────────────── */

static void
draw_cursor(wlt_Framebuffer *fb,
            uint32_t ox, uint32_t oy,
            wlt_cursor_style_t style, wlt_Color c)
{
    switch (style)
    {
        case WLT_CURSOR_BLOCK:
            /* Invert the cell by drawing an outline */
            for (uint32_t y = 0; y < WLT_RENDER_CELL_H; y++)
            {
                put_pixel(fb, ox + 0, oy + y, c);
                put_pixel(fb, ox + WLT_RENDER_CELL_W - 1, oy + y, c);
            }
            for (uint32_t x = 0; x < WLT_RENDER_CELL_W; x++)
            {
                put_pixel(fb, ox + x, oy + 0, c);
                put_pixel(fb, ox + x, oy + WLT_RENDER_CELL_H - 1, c);
            }
            break;
        case WLT_CURSOR_UNDERLINE:
            for (uint32_t x = 0; x < WLT_RENDER_CELL_W; x++)
                put_pixel(fb, ox + x, oy + WLT_RENDER_CELL_H - 2, c);
            break;
        case WLT_CURSOR_BAR:
            for (uint32_t y = 0; y < WLT_RENDER_CELL_H; y++)
                put_pixel(fb, ox + 1, oy + y, c);
            break;
    }
}

/* ─── Main Render Entry ──────────────────────────────── */

wlt_terminal_error_t
wlt_render_draw(wlt_Terminal *term, wlt_Framebuffer *fb)
{
    if (term == NULL || fb == NULL || fb->data == NULL)
        return WLT_TERMINAL_ERR_INVALID_ARG;

    /* Clear entire framebuffer to default background */
    fill_rect(fb, 0, 0, fb->width, fb->height, term->default_bg);

    /* Walk every cell. For now we always redraw fully; a real
     * compositor would skip cells without the dirty bit set. */
    for (uint32_t r = 0; r < term->rows; r++)
    {
        uint32_t y = r * WLT_RENDER_CELL_H;
        if (y >= fb->height) break;
        for (uint32_t c = 0; c < term->cols; c++)
        {
            uint32_t x = c * WLT_RENDER_CELL_W;
            if (x >= fb->width) break;

            const wlt_Cell *cell = &term->grid[r * term->cols + c];
            wlt_Color fg = cell_fg(term, cell);
            wlt_Color bg = cell_bg(term, cell);
            if (cell->reverse) swap_colors(&fg, &bg);

            draw_glyph(fb, x, y,
                       cell->codepoint ? cell->codepoint : ' ',
                       fg, bg, cell->bold, cell->underline);

            /* Selection highlight */
            if (term->has_selection &&
                r >= term->sel_start_row && r <= term->sel_end_row)
            {
                bool in_sel = false;
                if (r == term->sel_start_row && r == term->sel_end_row)
                    in_sel = (c >= term->sel_start_col &&
                              c <= term->sel_end_col);
                else if (r == term->sel_start_row)
                    in_sel = (c >= term->sel_start_col);
                else if (r == term->sel_end_row)
                    in_sel = (c <= term->sel_end_col);
                else
                    in_sel = true;
                if (in_sel)
                    fill_rect(fb, x, y,
                              WLT_RENDER_CELL_W, WLT_RENDER_CELL_H,
                              term->selection_color);
            }
        }
    }

    /* Cursor */
    if (term->cursor_visible &&
        term->cursor.row < term->rows &&
        term->cursor.col < term->cols)
    {
        uint32_t cx = term->cursor.col * WLT_RENDER_CELL_W;
        uint32_t cy = term->cursor.row * WLT_RENDER_CELL_H;
        draw_cursor(fb, cx, cy, term->cursor_style, term->cursor_color);
    }

    term->full_redraw = false;
    return WLT_TERMINAL_OK;
}
