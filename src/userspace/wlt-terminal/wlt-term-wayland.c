/**
 * @file wlt-term-wayland.c
 * @brief WLTIOS Terminal — Wayland client version
 * @purpose Render terminal text into a Wayland surface (compositor-managed)
 *
 * This replaces the direct-fb0 writer with a proper Wayland client.
 * The compositor owns the DRM display; the terminal owns its wl_buffer.
 * No page-flip race — the compositor composites the terminal's buffer.
 *
 * Reuses from wlt-term-main.c:
 *   - Linux kernel font_8x16 (96 chars, 8x16, 2x scale = 16x32 per glyph)
 *   - PTY spawn (wlt_pty_* library API + /bin/sh)
 *   - Grid buffer + cursor
 *   - ANSI CSI parser
 *
 * New from wayland_test.c:
 *   - Wayland client setup (connect, registry, bind compositor + shm + xdg)
 *   - wl_surface + xdg_toplevel
 *   - wl_shm_pool + wl_buffer (shared memory pixel buffer)
 *   - Render glyphs into shm buffer, attach to surface, commit
 *
 * Build: gcc -O2 $(pkg-config --cflags wayland-client) \
 *          wlt-term-wayland.c $(pkg-config --libs wayland-client) -lutil -o wlt-terminal
 * Run:   WAYLAND_DISPLAY=wayland-0 XDG_RUNTIME_DIR=/run wlt-terminal
 */

