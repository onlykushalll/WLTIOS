/* ═══════════════════════════════════════════════════════════════════════
 *  SHM BUFFER + RENDERING
 * ═══════════════════════════════════════════════════════════════════════ */
static int create_shm_buffer(void) {
    int stride = WIN_W * 4;  /* 32bpp BGRA */
    int size = stride * WIN_H;
    char template[] = "/run/wayland-shm-XXXXXX";
    shm_fd = mkostemp(template, O_CLOEXEC);
    if (shm_fd < 0) return -1;
    unlink(template);
    if (ftruncate(shm_fd, size) < 0) { close(shm_fd); return -1; }
    shm_pixels = mmap(NULL, size, PROT_READ | PROT_WRITE, MAP_SHARED, shm_fd, 0);
    if (shm_pixels == MAP_FAILED) { close(shm_fd); return -1; }

    struct wl_shm_pool *pool = wl_shm_create_pool(shm, shm_fd, size);
    buffer = wl_shm_pool_create_buffer(pool, 0, WIN_W, WIN_H, stride, WL_SHM_FORMAT_XRGB8888);
    wl_shm_pool_destroy(pool);
    return 0;
}

static void put_pixel(int x, int y, uint8_t r, uint8_t g, uint8_t b) {
    if (x < 0 || x >= WIN_W || y < 0 || y >= WIN_H) return;
    /* BGRA: B=0, G=1, R=2, A=3 (XRGB8888 on little-endian) */
    shm_pixels[y * WIN_W + x] = (0xFF << 24) | (r << 16) | (g << 8) | b;
}

static void fill_rect(int x0, int y0, int w, int h, uint8_t r, uint8_t g, uint8_t b) {
    for (int y = y0; y < y0 + h && y < WIN_H; y++)
        for (int x = x0; x < x0 + w && x < WIN_W; x++)
            put_pixel(x, y, r, g, b);
}

static void draw_char(int px, int py, char ch, uint8_t r, uint8_t g, uint8_t b) {
    int idx = ch - 32;
    if (idx < 0 || idx >= 96) idx = 0;
    const uint8_t *glyph = font8x16[idx];
    for (int row = 0; row < FONT_H; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < FONT_W; col++) {
            if (bits & (0x80 >> col)) {
                for (int sy = 0; sy < SCALE; sy++)
                    for (int sx = 0; sx < SCALE; sx++)
                        put_pixel(px + col*SCALE + sx, py + row*SCALE + sy, r, g, b);
            }
        }
    }
}

static void render_grid(void) {
    /* Black background */
    fill_rect(0, 0, WIN_W, WIN_H, 0x00, 0x00, 0x00);
    /* Green border (4px) */
    fill_rect(0, 0, WIN_W, 4, 0x00, 0xFF, 0x00);
    fill_rect(0, WIN_H-4, WIN_W, 4, 0x00, 0xFF, 0x00);
    fill_rect(0, 0, 4, WIN_H, 0x00, 0xFF, 0x00);
    fill_rect(WIN_W-4, 0, 4, WIN_H, 0x00, 0xFF, 0x00);
    /* Text */
    for (int row = 0; row < ROWS; row++)
        for (int col = 0; col < COLS; col++) {
            char ch = grid[row][col];
            if (ch == ' ') continue;
            draw_char(4 + col * CELL_W, 4 + row * CELL_H, ch, 0x00, 0xFF, 0x00);
        }
}

/* ═══════════════════════════════════════════════════════════════════════
 *  MAIN
 * ═══════════════════════════════════════════════════════════════════════ */
int main(void) {
    fprintf(stderr, "[wlt-term] starting (Wayland client, kernel font_8x16)\n");
    signal(SIGTERM, on_sig);
    signal(SIGINT, on_sig);

    /* Connect to Wayland */
    display = wl_display_connect(NULL);
    if (!display) {
        fprintf(stderr, "[wlt-term] FATAL: cannot connect to Wayland (%s)\n", strerror(errno));
        return 1;
    }
    fprintf(stderr, "[wlt-term] Connected to Wayland\n");

    struct wl_registry *registry = wl_display_get_registry(display);
    wl_registry_add_listener(registry, &registry_listener, NULL);
    wl_display_roundtrip(display);

    if (!compositor || !shm || !xdg_wm_base) {
        fprintf(stderr, "[wlt-term] FATAL: missing wl_compositor/wl_shm/xdg_wm_base\n");
        return 1;
    }
    xdg_wm_base_add_listener(xdg_wm_base, &xdg_wm_base_listener, NULL);
    fprintf(stderr, "[wlt-term] Got compositor + shm + xdg_wm_base\n");

    /* Create SHM buffer */
    if (create_shm_buffer() < 0) {
        fprintf(stderr, "[wlt-term] FATAL: cannot create shm buffer\n");
        return 1;
    }
    fprintf(stderr, "[wlt-term] SHM buffer created (%dx%d)\n", WIN_W, WIN_H);

    /* Create surface + XDG toplevel */
    surface = wl_compositor_create_surface(compositor);
    xdg_surface = xdg_wm_base_get_xdg_surface(xdg_wm_base, surface);
    xdg_surface_add_listener(xdg_surface, &xdg_surface_listener, NULL);
    xdg_toplevel = xdg_surface_get_toplevel(xdg_surface);
    xdg_toplevel_add_listener(xdg_toplevel, &xdg_toplevel_listener, NULL);
    xdg_toplevel_set_title(xdg_toplevel, "WLTIOS Terminal");
    wl_surface_commit(surface);
    wl_display_roundtrip(display);
    fprintf(stderr, "[wlt-term] Surface + toplevel created\n");

    /* Banner */
    grid_clear();
    const char *banner[] = {
        "WLTIOS Terminal v3.0 (Wayland)",
        "===============================",
        "",
        "Kernel font: 8x16 (Linux fbcon)",
        "Render: Wayland shm buffer",
        "Compositor: DRM backend",
        "",
        "$ ",
        NULL
    };
    for (int i = 0; banner[i] && i < ROWS; i++)
        for (int j = 0; banner[i][j] && j < COLS; j++)
            grid[i][j] = banner[i][j];
    cur_row = 8; cur_col = 2;

    /* Spawn PTY via the spec'd wlt-terminal pty.c library (wlt_pty_* API).
     * The library owns openpty/fork/exec, initial window size and reaping;
     * the terminal keeps only the master handle for poll/read/write. */
    wlt_Pty *pty = NULL;
    wlt_pty_error_t prc = wlt_pty_create(&pty, NULL, (uint32_t)COLS, (uint32_t)ROWS);
    if (prc != WLT_PTY_OK) {
        fprintf(stderr, "[wlt-term] wlt_pty_create failed: %s\n", wlt_pty_error_str(prc));
        return 1;
    }
    fprintf(stderr, "[wlt-term] PTY spawned (pid=%d)\n", (int)wlt_pty_pid(pty));

    /* Launch file manager + status bar + kairos as additional Wayland clients */
    pid_t fm_pid = fork();
    if (fm_pid == 0) { execl("/usr/bin/wlt-filemanager", "wlt-filemanager", NULL); _exit(127); }
    fprintf(stderr, "[wlt-term] file manager launched (pid=%d)\n", fm_pid);

    pid_t bar_pid = fork();
    if (bar_pid == 0) { execl("/usr/bin/wlt-statusbar", "wlt-statusbar", NULL); _exit(127); }
    fprintf(stderr, "[wlt-term] status bar launched (pid=%d)\n", bar_pid);

    pid_t kairos_pid = fork();
    if (kairos_pid == 0) { execl("/usr/bin/kairos-window", "kairos-window", NULL); _exit(127); }
    fprintf(stderr, "[wlt-term] kairos window launched (pid=%d)\n", kairos_pid);

    pid_t settings_pid = fork();
    if (settings_pid == 0) { execl("/usr/bin/wlt-settings", "wlt-settings", NULL); _exit(127); }
    fprintf(stderr, "[wlt-term] settings app launched (pid=%d)\n", settings_pid);

    /* Main loop: poll PTY + dispatch Wayland */
    struct pollfd pfd = { .fd = wlt_pty_fd(pty), .events = POLLIN };
    while (running) {
        /* Process Wayland events */
        while (wl_display_prepare_read(display) != 0)
            wl_display_dispatch_pending(display);
        wl_display_flush(display);
        wl_display_read_events(display);
        wl_display_dispatch_pending(display);

        /* Poll PTY (non-blocking, 33ms timeout for ~30fps) */
        int pr = poll(&pfd, 1, 33);
        if (pr > 0 && (pfd.revents & POLLIN)) {
            char buf[4096];
            size_t n = 0;
            wlt_pty_error_t rrc = wlt_pty_read(pty, (uint8_t *)buf, sizeof(buf), &n);
            if (rrc == WLT_PTY_OK && n > 0) {
                for (size_t i = 0; i < n; i++) process_byte(buf[i]);
                needs_redraw = 1;
            } else if (rrc == WLT_PTY_ERR_CLOSED) break;
        }

        /* Render + commit only after configured */
        if (needs_redraw && configured) {
            render_grid();
            wl_surface_attach(surface, buffer, 0, 0);
            wl_surface_damage(surface, 0, 0, WIN_W, WIN_H);
            wl_surface_commit(surface);
            needs_redraw = 0;
        }
    }

    fprintf(stderr, "[wlt-term] exiting\n");
    wlt_pty_destroy(pty);
    return 0;
}
