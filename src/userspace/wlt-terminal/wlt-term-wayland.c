/* ═══════════════════════════════════════════════════════════════════════
 *  LAYOUT
 * ═══════════════════════════════════════════════════════════════════════ */
#define COLS    60
#define ROWS    18
#define FONT_W  8
#define FONT_H  16
#define SCALE   2        /* 2x scale → 16x32 per glyph */
#define CELL_W  ((FONT_W + 1) * SCALE)   /* 18 */
#define CELL_H  ((FONT_H + 1) * SCALE)   /* 34 */
#define WIN_W   (COLS * CELL_W)          /* 1080 */
#define WIN_H   (ROWS * CELL_H)          /* 612 */

/* ═══════════════════════════════════════════════════════════════════════
 *  GRID + ANSI (same as wlt-term-main.c)
 * ═══════════════════════════════════════════════════════════════════════ */
static char grid[ROWS][COLS];
static int cur_row = 0, cur_col = 0;

static void grid_clear(void) { memset(grid, ' ', sizeof(grid)); cur_row = 0; cur_col = 0; }
static void grid_scroll(void) {
    memmove(grid[0], grid[1], sizeof(grid) - sizeof(grid[0]));
    memset(grid[ROWS-1], ' ', sizeof(grid[0]));
    if (cur_row > 0) cur_row--;
}
static void grid_newline(void) { cur_col = 0; cur_row++; if (cur_row >= ROWS) grid_scroll(); }
static void grid_putc(char c) {
    if (c == '\n') { grid_newline(); return; }
    if (c == '\r') { cur_col = 0; return; }
    if (c == '\b') { if (cur_col > 0) cur_col--; return; }
    if (c == '\t') { cur_col = (cur_col + 8) & ~7; if (cur_col >= COLS) grid_newline(); return; }
    if (cur_col >= COLS) grid_newline();
    if (cur_row >= ROWS) grid_scroll();
    if (c >= 32 && c < 127) { grid[cur_row][cur_col] = c; cur_col++; }
}

enum { ANSI_GROUND, ANSI_ESC, ANSI_CSI };
static int ansi_state = ANSI_GROUND, ansi_param = 0, ansi_has_param = 0;
static void ansi_reset(void) { ansi_state = ANSI_GROUND; ansi_param = 0; ansi_has_param = 0; }

static void ansi_handle_csi_final(char final) {
    int p = ansi_has_param ? ansi_param : 0;
    switch (final) {
        case 'J': if (p == 2) grid_clear();
                  else if (p == 0) { for (int c=cur_col;c<COLS;c++) grid[cur_row][c]=' ';
                                     for (int r=cur_row+1;r<ROWS;r++) memset(grid[r],' ',COLS); }
                  break;
        case 'K': if (p == 0) for (int c=cur_col;c<COLS;c++) grid[cur_row][c]=' ';
                  else if (p == 1) for (int c=0;c<=cur_col&&c<COLS;c++) grid[cur_row][c]=' ';
                  else if (p == 2) memset(grid[cur_row],' ',COLS);
                  break;
        case 'H': case 'f': cur_row = ansi_has_param ? (ansi_param-1) : 0; cur_col = 0;
                  if (cur_row < 0) cur_row = 0; if (cur_row >= ROWS) cur_row = ROWS-1; break;
    }
}

static void process_byte(char c) {
    switch (ansi_state) {
    case ANSI_GROUND:
        if (c == 0x1B) { ansi_state = ANSI_ESC; return; }
        grid_putc(c); break;
    case ANSI_ESC:
        if (c == '[') { ansi_state = ANSI_CSI; ansi_param = 0; ansi_has_param = 0; return; }
        ansi_reset(); break;
    case ANSI_CSI:
        if (c >= '0' && c <= '9') { ansi_param = ansi_param*10 + (c-'0'); ansi_has_param = 1; return; }
        if (c == ';') { ansi_has_param = 1; return; }
        if (c >= '@' && c <= '~') { ansi_handle_csi_final(c); ansi_reset(); return; }
        break;
    }
}

